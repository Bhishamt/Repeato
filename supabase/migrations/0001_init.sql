-- Repeato — production (PostgreSQL / Supabase) schema.
--
-- Column semantics are identical to the SQLite mirror in lib/schema.ts so one
-- application code path serves both engines: money is integer minor units
-- (paise), points are integers, and a balance is always SUM(ledger.delta) —
-- never a stored column.
--
-- Identity columns (not uuids) are deliberate: the app issues its own session
-- cookies and scrypt passwords (see lib/auth.ts), so ids never cross a trust
-- boundary and never appear in a public URL. Integers keep both engines
-- byte-compatible, which is what lets the same service layer run on each.
-- To adopt Supabase Auth later, add `auth_user_id uuid unique references
-- auth.users (id)` to users and redefine public.current_user_id() (0002).

create extension if not exists "pgcrypto";

create type user_role         as enum ('owner', 'staff', 'customer', 'admin');
create type account_status    as enum ('active', 'suspended');
create type business_status   as enum ('pending', 'active', 'suspended');
create type member_role       as enum ('owner', 'staff');
create type purchase_status   as enum ('verified', 'reversed');
create type ledger_kind       as enum ('earn', 'redeem', 'reverse', 'adjust', 'bonus');
create type redemption_status as enum ('issued', 'redeemed', 'cancelled');

create table users (
  id            bigint generated by default as identity primary key,
  email         text not null,
  name          text not null,
  phone         text,
  password_hash text not null,
  role          user_role not null default 'customer',
  status        account_status not null default 'active',
  created_at    timestamptz not null default now()
);
-- Case-insensitive uniqueness: signup lowercases before insert, this enforces it.
create unique index users_email_lower on users (lower(email));

create table sessions (
  token_hash text primary key,
  user_id    bigint not null references users (id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index sessions_user on sessions (user_id);
create index sessions_expiry on sessions (expires_at);

create table businesses (
  id                 bigint generated by default as identity primary key,
  name               text not null,
  slug               text not null unique,
  category           text not null default 'Cafe',
  description        text,
  brand_color        text not null default '#17553f',
  address            text,
  city               text,
  phone              text,
  status             business_status not null default 'active',
  points_per_100     integer not null default 10   check (points_per_100 >= 0),
  min_purchase_paise integer not null default 10000 check (min_purchase_paise >= 0),
  signup_bonus       integer not null default 20   check (signup_bonus >= 0),
  min_redeem_points  integer not null default 100  check (min_redeem_points >= 0),
  max_points_per_txn integer not null default 1000 check (max_points_per_txn > 0),
  created_at         timestamptz not null default now()
);
create index businesses_status on businesses (status);

create table business_members (
  user_id     bigint not null references users (id) on delete cascade,
  business_id bigint not null references businesses (id) on delete cascade,
  role        member_role not null default 'staff',
  created_at  timestamptz not null default now(),
  primary key (user_id, business_id)
);
create index members_business on business_members (business_id);

create table business_customers (
  business_id bigint not null references businesses (id) on delete cascade,
  user_id     bigint not null references users (id) on delete cascade,
  joined_at   timestamptz not null default now(),
  primary key (business_id, user_id)
);
create index bc_user on business_customers (user_id);
create index bc_business on business_customers (business_id);

create table categories (
  id          bigint generated by default as identity primary key,
  business_id bigint not null references businesses (id) on delete cascade,
  name        text not null,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now(),
  unique (business_id, name)
);

create table products (
  id              bigint generated by default as identity primary key,
  business_id     bigint not null references businesses (id) on delete cascade,
  category_id     bigint references categories (id) on delete set null,
  name            text not null,
  description     text,
  price_paise     integer not null check (price_paise >= 0),
  points_override integer check (points_override is null or points_override >= 0),
  available       integer not null default 1 check (available in (0, 1)),
  archived        integer not null default 0 check (archived in (0, 1)),
  created_at      timestamptz not null default now()
);
create index products_business on products (business_id, archived);

create table rewards (
  id                 bigint generated by default as identity primary key,
  business_id        bigint not null references businesses (id) on delete cascade,
  name               text not null,
  description        text,
  points_cost        integer not null check (points_cost > 0),
  active             integer not null default 1 check (active in (0, 1)),
  stock              integer check (stock is null or stock >= 0),
  per_customer_limit integer check (per_customer_limit is null or per_customer_limit > 0),
  valid_until        date,
  created_at         timestamptz not null default now()
);
create index rewards_business on rewards (business_id, active);

create table purchases (
  id              bigint generated by default as identity primary key,
  business_id     bigint not null references businesses (id) on delete cascade,
  customer_id     bigint not null references users (id),
  staff_id        bigint not null references users (id),
  amount_paise    integer not null check (amount_paise >= 0),
  points_awarded  integer not null check (points_awarded >= 0),
  status          purchase_status not null default 'verified',
  reference       text,
  note            text,
  idempotency_key text not null unique,
  created_at      timestamptz not null default now(),
  reversed_at     timestamptz
);
create index purchases_business on purchases (business_id, created_at desc);
create index purchases_customer on purchases (customer_id, created_at desc);

create table purchase_items (
  id               bigint generated by default as identity primary key,
  purchase_id      bigint not null references purchases (id) on delete cascade,
  product_id       bigint references products (id) on delete set null,
  name             text not null,
  unit_price_paise integer not null check (unit_price_paise >= 0),
  quantity         integer not null check (quantity > 0),
  points           integer not null check (points >= 0)
);
create index purchase_items_purchase on purchase_items (purchase_id);

create table redemptions (
  id           bigint generated by default as identity primary key,
  business_id  bigint not null references businesses (id) on delete cascade,
  customer_id  bigint not null references users (id),
  reward_id    bigint not null references rewards (id),
  points_spent integer not null check (points_spent > 0),
  token        text not null unique,
  status       redemption_status not null default 'issued',
  issued_at    timestamptz not null default now(),
  expires_at   timestamptz not null,
  redeemed_at  timestamptz,
  redeemed_by  bigint references users (id)
);
create index redemptions_business on redemptions (business_id, status, issued_at desc);
create index redemptions_customer on redemptions (customer_id, issued_at desc);

create table ledger (
  id            bigint generated by default as identity primary key,
  business_id   bigint not null references businesses (id) on delete cascade,
  customer_id   bigint not null references users (id) on delete cascade,
  purchase_id   bigint references purchases (id),
  redemption_id bigint references redemptions (id),
  delta         integer not null check (delta <> 0),
  kind          ledger_kind not null,
  note          text,
  created_at    timestamptz not null default now()
);
create index ledger_account on ledger (business_id, customer_id, created_at desc);

create table notifications (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references users (id) on delete cascade,
  business_id bigint references businesses (id) on delete cascade,
  title       text not null,
  body        text,
  read_at     timestamptz,
  created_at  timestamptz not null default now()
);
create index notifications_user on notifications (user_id, created_at desc);

create table audit_log (
  id         bigint generated by default as identity primary key,
  actor_id   bigint references users (id) on delete set null,
  action     text not null,
  entity     text not null,
  entity_id  text,
  meta       jsonb,
  created_at timestamptz not null default now()
);
create index audit_created on audit_log (created_at desc);

-- Derived balance, the single source of truth for a customer's points.
create view account_balances as
  select business_id, customer_id, sum(delta)::integer as balance
  from ledger
  group by business_id, customer_id;

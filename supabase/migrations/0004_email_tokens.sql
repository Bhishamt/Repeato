-- Email verification and password reset tokens.
-- Only the SHA-256 hash of a token is stored, so a database leak cannot be
-- replayed against the live site. Tokens are single-use and time limited.

alter table users add column if not exists email_verified integer not null default 0
  check (email_verified in (0, 1));

create table if not exists email_tokens (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references users (id) on delete cascade,
  kind       text not null check (kind in ('verify', 'reset')),
  token_hash text not null unique,
  expires_at timestamptz not null,
  used_at    timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists email_tokens_user on email_tokens (user_id, kind);
create index if not exists email_tokens_expiry on email_tokens (expires_at);

alter table email_tokens enable row level security;

-- The least-privilege application role from 0003 needs access. Anonymous and
-- authenticated API callers get no policy, so PostgREST cannot read this table.
do $$
begin
  if exists (select 1 from pg_roles where rolname = 'repeato_app') then
    grant select, insert, update on email_tokens to repeato_app;
    grant usage, select on sequence email_tokens_id_seq to repeato_app;
    drop policy if exists app_role_access on email_tokens;
    create policy app_role_access on email_tokens for all to repeato_app using (true) with check (true);
  end if;
end $$;
